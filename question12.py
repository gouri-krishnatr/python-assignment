# Difference between List and Tuple

# List:
# 1. List is mutable (can be changed).
# 2. List uses square brackets [].

# Tuple:
# 1. Tuple is immutable (cannot be changed).
# 2. Tuple uses parentheses ().

# Example:
my_list = [1, 2, 3]
my_tuple = (1, 2, 3)

print("List:", my_list)
print("Tuple:", my_tuple)